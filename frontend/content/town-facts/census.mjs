// Pulls the housing numbers every town facts file needs from Census ACS 5-year data,
// so research agents don't spend tokens reading Census pages.
// Run from ./frontend:
//   node content/town-facts/census.mjs --geocode "4600 Eastern Ave, Cincinnati, OH"   -> tract / block group / place ids
//   node content/town-facts/census.mjs 14000US39061004703 14000US39061004800          -> markdown bullets (geographies summed)
// Geo id prefixes: 14000US = tract (11 digits), 15000US = block group (12), 16000US = place (7), 06000US = county subdivision (10).
const API = 'https://api.censusreporter.org/1.0/data/show/latest';
const TABLES = ['B25034', 'B25035', 'B25024', 'B25003', 'B25040'];

const args = process.argv.slice(2);
if (!args.length) {
  console.log('Usage: --geocode "address"  |  <geo ids...>');
  process.exit(1);
}

if (args[0] === '--geocode') {
  const url = `https://geocoding.geo.census.gov/geocoder/geographies/onelineaddress?address=${encodeURIComponent(args[1])}&benchmark=Public_AR_Current&vintage=Current_Current&format=json`;
  const m = (await (await fetch(url)).json()).result.addressMatches[0];
  if (!m) { console.log('No match'); process.exit(1); }
  const g = m.geographies;
  const first = k => (g[k] ?? [])[0];
  console.log(`Matched: ${m.matchedAddress}`);
  if (first('Census Tracts')) console.log(`Tract ${first('Census Tracts').NAME}: 14000US${first('Census Tracts').GEOID}`);
  const bgKey = Object.keys(g).find(k => /Block Groups/.test(k));
  if (bgKey && g[bgKey][0]) console.log(`Block group: 15000US${g[bgKey][0].GEOID}`);
  else { const blk = Object.keys(g).find(k => /Census Blocks/.test(k)); if (blk && g[blk][0]) console.log(`Block group: 15000US${g[blk][0].GEOID.slice(0, 12)}`); }
  if (first('Incorporated Places')) console.log(`Place ${first('Incorporated Places').NAME}: 16000US${first('Incorporated Places').GEOID}`);
  if (first('Census Designated Places')) console.log(`CDP ${first('Census Designated Places').NAME}: 16000US${first('Census Designated Places').GEOID}`);
  if (first('County Subdivisions')) console.log(`County subdivision ${first('County Subdivisions').NAME}: 06000US${first('County Subdivisions').GEOID}`);
  process.exit(0);
}

const geoIds = args;
// censusreporter blocks generic user agents and asks for a project-specific one.
const res = await (await fetch(`${API}?table_ids=${TABLES.join(',')}&geo_ids=${geoIds.join(',')}`, {
  headers: { 'User-Agent': 'degree-of-comfort-town-facts/1.0' },
})).json();
if (res.error) { console.log(res.error); process.exit(1); }

// Sum each column across geographies (medians are listed per geography instead).
const sum = (table, col) => geoIds.reduce((n, id) => n + (res.data[id]?.[table]?.estimate?.[col] ?? 0), 0);
const cols = table => Object.entries(res.tables[table].columns).map(([id, c]) => ({ id, name: c.name }));
const pct = (n, d) => (d ? `${((100 * n) / d).toFixed(1)}%` : 'n/a');
const byName = (table, test) => cols(table).filter(c => test(c.name)).reduce((n, c) => n + sum(table, c.id), 0);

const units = sum('B25034', 'B25034001');
const pre1940 = byName('B25034', n => /1939 or earlier/.test(n));
const y1940to1959 = byName('B25034', n => /19[45]\d to 19[45]9/.test(n));
const y1960to1979 = byName('B25034', n => /19[67]\d to 19[67]9/.test(n));
const y1980to1999 = byName('B25034', n => /19[89]\d to 19[89]9/.test(n));
const y2000on = byName('B25034', n => /20\d\d (to|or later)/.test(n));

const detached = byName('B25024', n => /1, detached/.test(n));
const attached = byName('B25024', n => /1, attached/.test(n));
const two = byName('B25024', n => /^2$/.test(n.trim()));
const threeFour = byName('B25024', n => /3 or 4/.test(n));
const fivePlus = byName('B25024', n => /^(5 to 9|10 to 19|20 to 49|50 or more)$/.test(n.trim()));
const fiftyPlus = byName('B25024', n => /50 or more/.test(n));
const mobile = byName('B25024', n => /Mobile home/i.test(n));

const occupied = sum('B25003', 'B25003001');
const renter = byName('B25003', n => /Renter/.test(n));

const heatTotal = sum('B25040', 'B25040001');
const gas = byName('B25040', n => /Utility gas/.test(n));
const electric = byName('B25040', n => /^Electricity$/.test(n.trim()));
const propane = byName('B25040', n => /Bottled|propane/i.test(n));
const oil = byName('B25040', n => /Fuel oil/.test(n));

const names = geoIds.map(id => res.geography[id]?.name ?? id);
const medians = geoIds.map(id => `${res.geography[id]?.name ?? id}: ${res.data[id]?.B25035?.estimate?.B25035001 ?? 'n/a'}`);
const src = geoIds.map(id => `https://censusreporter.org/profiles/${id}/`).join(' , ');

console.log(`<!-- Census block generated by content/town-facts/census.mjs (${res.release.name}, ${res.release.years}) -->`);
console.log(`- **Geography:** ${names.join('; ')}. Source: ${src}`);
console.log(`- **Housing units:** ${units.toLocaleString('en-US')}. Median year built: ${medians.join('; ')}. (Census lists 1939 as the floor; a median of 1939 or 1938 means "1939 or earlier".)`);
console.log(`- **Year built:** 1939 or earlier ${pct(pre1940, units)}; 1940-59 ${pct(y1940to1959, units)}; 1960-79 ${pct(y1960to1979, units)}; 1980-99 ${pct(y1980to1999, units)}; 2000 or later ${pct(y2000on, units)}.`);
console.log(`- **Units in structure:** single-family detached ${pct(detached, units)} (${detached}); attached ${pct(attached, units)}; two-unit ${pct(two, units)}; 3-4 units ${pct(threeFour, units)}; 5+ units ${pct(fivePlus, units)} (50+ units: ${fiftyPlus}); mobile homes ${mobile}.`);
console.log(`- **Tenure:** ${occupied.toLocaleString('en-US')} occupied units; ${pct(renter, occupied)} rented, ${pct(occupied - renter, occupied)} owner-occupied.`);
console.log(`- **Heating fuel:** utility gas ${pct(gas, heatTotal)}; electricity ${pct(electric, heatTotal)}; propane ${pct(propane, heatTotal)}; fuel oil ${pct(oil, heatTotal)}.`);
console.log(`- Small geographies have wide margins of error; treat block-group figures as approximate.`);

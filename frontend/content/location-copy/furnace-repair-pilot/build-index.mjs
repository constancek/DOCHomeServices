// Regenerates index.ts so every finished town file in this folder is wired in.
// Run from ./frontend:  node content/location-copy/furnace-repair-pilot/build-index.mjs
// Agents only create their own <slug>.ts file and never edit index.ts, so
// parallel runs can't overwrite each other. Files ending in .draft.ts (failed
// checks) are skipped.
import fs from 'fs';
import path from 'path';
import { fileURLToPath } from 'url';

const dir = path.dirname(fileURLToPath(import.meta.url));
const entries = [];
for (const file of fs.readdirSync(dir).sort()) {
  if (!file.endsWith('.ts') || file === 'index.ts' || file.endsWith('.draft.ts')) continue;
  const src = fs.readFileSync(path.join(dir, file), 'utf8');
  const m = src.match(/export const (\w+): LocationServiceCopy/);
  if (!m) { console.warn(`skipped ${file}: no "export const X: LocationServiceCopy"`); continue; }
  entries.push({ slug: file.replace(/\.ts$/, ''), name: m[1], file: file.replace(/\.ts$/, '') });
}
const out = `// GENERATED by build-index.mjs. Do not edit by hand; re-run the script instead.
import type { LocationServiceCopy } from '@/components/LocationServicePage';
${entries.map(e => `import { ${e.name} } from './${e.file}';`).join('\n')}

export const furnaceRepairPilot: Record<string, LocationServiceCopy> = {
${entries.map(e => `  '${e.slug}': ${e.name},`).join('\n')}
};
`;
fs.writeFileSync(path.join(dir, 'index.ts'), out);
console.log(`index.ts: ${entries.length} towns wired in`);
